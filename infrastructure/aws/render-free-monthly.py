"""Render the inline Lambda source into the no-artifact-bucket CloudFormation template."""

from __future__ import annotations

import argparse
from pathlib import Path


def render(template: Path, handler: Path, output: Path) -> None:
    template_text = template.read_text(encoding="utf-8")
    source = handler.read_text(encoding="utf-8").rstrip()
    marker = "          # Generated by infrastructure/aws/render-free-monthly.py.\n"
    if template_text.count(marker) != 1:
        raise ValueError("CloudFormation template must contain exactly one generated-code marker.")
    indented = "".join(f"          {line}\n" for line in source.splitlines())
    output.write_text(template_text.replace(marker, indented), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--template", type=Path, required=True)
    parser.add_argument("--handler", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    render(args.template, args.handler, args.output)


if __name__ == "__main__":
    main()
